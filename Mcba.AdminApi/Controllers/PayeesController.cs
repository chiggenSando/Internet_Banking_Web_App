using Mcba.AdminApi.Repositories;
using Mcba.Data.Models;
using Microsoft.AspNetCore.Mvc;

namespace Mcba.AdminApi.Controllers;

/// <summary>
/// Endpoints for viewing and creating bill pay payees.
/// </summary>
[ApiController]
[Route("api/[controller]")]
public class PayeesController(IPayeeRepository _repo) : ControllerBase
{

    /// <summary>
    /// Lists payees ordered by name, optionally filtered by state.
    /// </summary>
    /// <param name="state">Australian state to filter by, e.g. <c>VIC</c>. Case-insensitive. Omit to return all payees.</param>
    /// <response code="200">The matching payees.</response>
    [HttpGet]
    public async Task<ActionResult<IEnumerable<Payee>>> GetAll([FromQuery] string? state)
    {
        return Ok(await _repo.GetAllAsync(state));
    }

    /// <summary>
    /// Gets a single payee.
    /// </summary>
    /// <param name="id">The payee ID.</param>
    /// <response code="200">The payee.</response>
    /// <response code="404">No payee exists with the given ID.</response>
    [HttpGet("{id}")]
    public async Task<ActionResult<Payee>> Get(int id)
    {
        var payee = await _repo.GetAsync(id);
        if (payee is null)
            return NotFound();
        return Ok(payee);
    }

    /// <summary>
    /// Creates a payee.
    /// </summary>
    /// <param name="payee">The payee to create. <see cref="Payee.PayeeID"/> is generated by the database.</param>
    /// <response code="201">The created payee, with a <c>Location</c> header pointing to it.</response>
    /// <response code="400">The payee failed validation.</response>
    [HttpPost]
    public async Task<ActionResult<Payee>> Create(Payee payee)
    {
        var created = await _repo.AddAsync(payee);
        return CreatedAtAction(nameof(Get), new { id = created.PayeeID }, created);
    }
}
